-- Agente de WhatsApp (Claude) para atencion a clientes y ventas.
--
-- ManyChat recibe el mensaje del cliente y lo reenvia a /api/agent/whatsapp
-- (External Request). ALFA OS responde 200 de inmediato, corre a Claude en
-- segundo plano y contesta por la API de ManyChat. Estas tablas guardan:
--
--   whatsapp_agent_conversations - una fila por contacto de ManyChat
--   whatsapp_agent_inbound       - cola de mensajes recibidos (lo que llega de ManyChat)
--   whatsapp_agent_messages      - transcripcion que se le manda a Claude, append-only
--
-- La transcripcion es append-only a proposito: Claude exige que el historial
-- que se le reenvia sea identico turno a turno (bloques de thinking y prompt
-- caching). `content` es `json` (no `jsonb`) para conservar el texto exacto
-- de los bloques que devolvio la API.
--
-- Todo lo escribe la ruta con el cliente admin (service_role). Las tablas
-- quedan con RLS activo, sin policies y sin grants para anon/authenticated:
-- nadie las lee desde el navegador.
--
-- Tambien agrega 'WhatsApp' a leads_source_check para que el agente registre
-- prospectos con su origen real.
--
-- Aplicado en sandbox (alfa-os-sandbox) el 2026-10-28; en ese proyecto el
-- check anterior tenia 'Prospectaci??n Directa' (acento corrompido) y quedo
-- corregido. NO APLICADO en produccion. Rollback exacto en
-- 20261028_whatsapp_agent_rollback.sql.

-- ---------------------------------------------------------------------------
-- Conversaciones
-- ---------------------------------------------------------------------------

create table if not exists public.whatsapp_agent_conversations (
  id bigint generated by default as identity primary key,
  manychat_subscriber_id text not null unique,
  phone text,
  contact_name text,
  client_id bigint references public.clients(id) on delete set null,
  lead_id bigint references public.leads(id) on delete set null,
  status text not null default 'active' check (status in ('active', 'handoff')),
  handoff_reason text,
  handoff_until timestamptz,
  -- Ultimo whatsapp_agent_inbound.id ya pasado a la transcripcion.
  last_inbound_processed_id bigint not null default 0,
  -- Candado de corrida: evita dos respuestas simultaneas al mismo contacto.
  run_token uuid,
  run_started_at timestamptz,
  last_inbound_at timestamptz,
  last_reply_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists whatsapp_agent_conversations_client_idx
  on public.whatsapp_agent_conversations (client_id);

-- ---------------------------------------------------------------------------
-- Cola de entrada
-- ---------------------------------------------------------------------------

create table if not exists public.whatsapp_agent_inbound (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.whatsapp_agent_conversations(id) on delete cascade,
  text text not null,
  received_at timestamptz not null default now()
);

create index if not exists whatsapp_agent_inbound_conversation_idx
  on public.whatsapp_agent_inbound (conversation_id, id);

-- ---------------------------------------------------------------------------
-- Transcripcion (append-only)
-- ---------------------------------------------------------------------------

create table if not exists public.whatsapp_agent_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.whatsapp_agent_conversations(id) on delete cascade,
  seq integer not null,
  role text not null check (role in ('user', 'assistant', 'system')),
  content json not null,
  model text,
  usage jsonb,
  created_at timestamptz not null default now(),
  unique (conversation_id, seq)
);

-- ---------------------------------------------------------------------------
-- Seguridad: solo service_role
-- ---------------------------------------------------------------------------

alter table public.whatsapp_agent_conversations enable row level security;
alter table public.whatsapp_agent_inbound enable row level security;
alter table public.whatsapp_agent_messages enable row level security;

revoke all on public.whatsapp_agent_conversations from anon, authenticated;
revoke all on public.whatsapp_agent_inbound from anon, authenticated;
revoke all on public.whatsapp_agent_messages from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Leads: origen WhatsApp
-- ---------------------------------------------------------------------------

alter table public.leads drop constraint if exists leads_source_check;
alter table public.leads
  add constraint leads_source_check
  check (source = any (array[
    'Landing Web'::text,
    'Referido'::text,
    'LinkedIn'::text,
    'Google'::text,
    'Prospectación Directa'::text,
    'Cliente Existente'::text,
    'WhatsApp'::text
  ]));
