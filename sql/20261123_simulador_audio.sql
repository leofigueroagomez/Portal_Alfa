-- Simulador de audio publico (/simulador-audio).
--
-- Quien no tiene sesion de ALFA deja nombre, correo y telefono, verifica el
-- correo con un codigo de 6 digitos y recibe un pase firmado en una cookie.
-- Al verificar se crea su prospecto en `leads`. Estas tablas guardan:
--
--   simulator_access  - una fila por correo: datos de contacto, codigo vigente
--                       (solo su hash), fecha de verificacion y lead ligado
--   simulator_designs - lo que el visitante diseño cuando pide propuesta
--
-- Los visitantes NO son usuarios de Supabase Auth a proposito: el trigger
-- handle_new_user_profile() deja como interno `comercial` a cualquier usuario
-- nuevo sin metadata de portal (ver docs/ai/SECURITY_RULES.md).
--
-- Todo lo escriben las rutas /api/simulador-audio/* con el cliente admin
-- (service_role). Las tablas quedan con RLS activo, sin policies y sin grants
-- para anon/authenticated: nadie las lee desde el navegador.
--
-- Tambien agrega 'Simulador de Audio' a leads_source_check.
--
-- Aplicado en produccion (Alfa IT) el 2026-11-23 con confirmacion de Leo.
-- No se probo antes en sandbox: el proyecto de sandbox ya no existe. Despues de
-- aplicarlo se verifico RLS activo, cero policies, grants solo para postgres y
-- service_role, y el check de leads con el origen nuevo.
-- Rollback en 20261123_simulador_audio_rollback.sql.

-- ---------------------------------------------------------------------------
-- Accesos
-- ---------------------------------------------------------------------------

create table if not exists public.simulator_access (
  id bigint generated by default as identity primary key,
  email text not null check (email = lower(email)),
  name text not null,
  phone text not null,
  -- HMAC del codigo vigente; el codigo en claro nunca se guarda.
  code_hash text,
  code_expires_at timestamptz,
  code_attempts integer not null default 0,
  code_sent_at timestamptz,
  verified_at timestamptz,
  lead_id bigint references public.leads(id) on delete set null,
  privacy_accepted_at timestamptz not null default now(),
  attribution jsonb,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists simulator_access_email_key
  on public.simulator_access (email);

-- ---------------------------------------------------------------------------
-- Diseños enviados con "Solicitar propuesta"
-- ---------------------------------------------------------------------------

create table if not exists public.simulator_designs (
  id bigint generated by default as identity primary key,
  access_id bigint not null references public.simulator_access(id) on delete cascade,
  lead_id bigint references public.leads(id) on delete set null,
  project_type text,
  note text,
  summary text not null,
  design jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists simulator_designs_access_idx
  on public.simulator_designs (access_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Seguridad: solo service_role
-- ---------------------------------------------------------------------------

alter table public.simulator_access enable row level security;
alter table public.simulator_designs enable row level security;

revoke all on public.simulator_access from anon, authenticated;
revoke all on public.simulator_designs from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Leads: origen Simulador de Audio
-- ---------------------------------------------------------------------------

alter table public.leads drop constraint if exists leads_source_check;
alter table public.leads
  add constraint leads_source_check
  check (source = any (array[
    'Landing Web'::text,
    'Referido'::text,
    'LinkedIn'::text,
    'Google'::text,
    'Prospectación Directa'::text,
    'Cliente Existente'::text,
    'WhatsApp'::text,
    'Simulador de Audio'::text
  ]));

notify pgrst, 'reload schema';
