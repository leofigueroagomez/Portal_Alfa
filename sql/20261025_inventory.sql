-- Inventario / Almacen (2026-10-25)
--
-- Existencias por producto y ubicacion con costo promedio ponderado en MXN y
-- un kardex de movimientos (in | out | adjust).
--
-- Reglas de diseno:
--   * inventory_items guarda el saldo vivo (cantidad + costo promedio MXN).
--   * inventory_movements es el kardex: cada movimiento guarda el saldo y el
--     costo promedio resultantes (quantity_after / average_cost_mxn_after).
--   * El saldo solo se mueve dentro de las funciones inventory_* de abajo, que
--     bloquean la fila del item (FOR UPDATE) para que dos salidas simultaneas
--     no dejen existencias negativas. Por eso estas tablas tienen solo policy
--     de lectura para authenticated (mas estricto que las beta_authenticated_*
--     de compras): la escritura entra por server actions con permiso
--     canManagePurchases + service_role.
--   * "Sobrante a almacen" (entrada con source_purchase_event_id) NO toca el
--     evento ni la linea de compra del proyecto: el costo ya cargado se queda
--     como esta.
--   * "Consumir de almacen" crea la salida y un project_purchase_events en MXN
--     al costo promedio del inventario, para que Vigia (vigia_v_cst01 /
--     vigia_v_cst05) lo lea como costo real. Los totales de la linea los
--     recalcula la app con recalculatePurchaseLineTotals
--     (lib/projectPurchases.ts), igual que cualquier otra compra.
--
-- Idempotente. No modifica tablas ni vistas existentes.

create table if not exists public.inventory_items (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  location text not null default 'Almacén principal',
  quantity_available numeric(14,2) not null default 0
    check (quantity_available >= 0),
  average_cost_mxn numeric(14,4) not null default 0
    check (average_cost_mxn >= 0),
  last_movement_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists inventory_items_product_location_key
  on public.inventory_items(product_id, location);

create index if not exists inventory_items_product_id_idx
  on public.inventory_items(product_id);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  inventory_item_id bigint not null references public.inventory_items(id) on delete restrict,
  product_id bigint not null references public.products(id) on delete restrict,
  location text not null,
  movement_type text not null check (movement_type in ('in', 'out', 'adjust')),
  -- in/out: siempre positiva. adjust: delta con signo (+ suma, - resta).
  quantity numeric(14,2) not null,
  unit_cost numeric(14,4) not null default 0 check (unit_cost >= 0),
  cost_currency text not null default 'MXN' check (cost_currency in ('USD', 'MXN')),
  exchange_rate numeric(14,4),
  unit_cost_mxn numeric(14,4) not null default 0 check (unit_cost_mxn >= 0),
  -- Valor absoluto del movimiento en MXN (abs(quantity) * unit_cost_mxn).
  total_cost_mxn numeric(14,2) not null default 0 check (total_cost_mxn >= 0),
  quantity_after numeric(14,2) not null check (quantity_after >= 0),
  average_cost_mxn_after numeric(14,4) not null check (average_cost_mxn_after >= 0),
  -- Entrada originada en una compra de proyecto (sobrante).
  source_purchase_event_id bigint references public.project_purchase_events(id) on delete set null,
  -- Salida: proyecto destino, linea y evento de compra generado.
  client_project_id bigint references public.client_projects(id) on delete set null,
  project_purchase_line_id bigint references public.project_purchase_lines(id) on delete set null,
  project_purchase_event_id bigint references public.project_purchase_events(id) on delete set null,
  supplier_id bigint references public.suppliers(id) on delete set null,
  invoice_reference text,
  notes text,
  created_by_user_id uuid references auth.users(id),
  created_at timestamptz not null default now(),
  constraint inventory_movements_quantity_sign check (
    (movement_type in ('in', 'out') and quantity > 0)
    or (movement_type = 'adjust' and quantity <> 0)
  ),
  constraint inventory_movements_exchange_rate check (
    cost_currency = 'MXN' or coalesce(exchange_rate, 0) > 0
  )
);

create index if not exists inventory_movements_item_created_idx
  on public.inventory_movements(inventory_item_id, created_at desc, id desc);

create index if not exists inventory_movements_product_created_idx
  on public.inventory_movements(product_id, created_at desc, id desc);

create index if not exists inventory_movements_source_event_idx
  on public.inventory_movements(source_purchase_event_id)
  where source_purchase_event_id is not null;

create index if not exists inventory_movements_client_project_idx
  on public.inventory_movements(client_project_id)
  where client_project_id is not null;

create unique index if not exists inventory_movements_project_event_key
  on public.inventory_movements(project_purchase_event_id)
  where project_purchase_event_id is not null;

-- RLS: lectura para usuarios autenticados; sin policies de escritura.
alter table public.inventory_items enable row level security;
alter table public.inventory_movements enable row level security;

drop policy if exists beta_authenticated_select on public.inventory_items;
create policy beta_authenticated_select
on public.inventory_items
for select
to authenticated
using (true);

drop policy if exists beta_authenticated_select on public.inventory_movements;
create policy beta_authenticated_select
on public.inventory_movements
for select
to authenticated
using (true);

revoke all on public.inventory_items from anon;
revoke all on public.inventory_movements from anon;

-- Vista de existencias (respeta RLS del llamante).
create or replace view public.inventory_v_stock
with (security_invoker = true) as
select
  i.id as inventory_item_id,
  i.product_id,
  i.location,
  i.quantity_available,
  i.average_cost_mxn,
  round(i.quantity_available * i.average_cost_mxn, 2) as stock_value_mxn,
  i.last_movement_at,
  p.brand as product_brand,
  p.model as product_model,
  p.name as product_name,
  p.unit_name,
  p.sku as product_sku
from public.inventory_items i
join public.products p on p.id = i.product_id;

revoke all on public.inventory_v_stock from anon;
grant select on public.inventory_v_stock to authenticated;

-- Item por producto + ubicacion (crea si no existe) y lo bloquea.
create or replace function public.inventory_lock_item(
  p_product_id bigint,
  p_location text
) returns public.inventory_items
language plpgsql
set search_path = public
as $$
declare
  v_location text := coalesce(nullif(btrim(p_location), ''), 'Almacén principal');
  v_item public.inventory_items;
begin
  insert into public.inventory_items (product_id, location)
  values (p_product_id, v_location)
  on conflict (product_id, location) do nothing;

  select * into v_item
  from public.inventory_items
  where product_id = p_product_id and location = v_location
  for update;

  return v_item;
end;
$$;

-- Entrada (compra directa o sobrante de un evento de compra de proyecto).
create or replace function public.inventory_register_entry(
  p_product_id bigint,
  p_location text,
  p_quantity numeric,
  p_unit_cost numeric,
  p_cost_currency text,
  p_exchange_rate numeric,
  p_source_purchase_event_id bigint default null,
  p_supplier_id bigint default null,
  p_invoice_reference text default null,
  p_notes text default null,
  p_created_by_user_id uuid default null
) returns public.inventory_movements
language plpgsql
set search_path = public
as $$
declare
  v_currency text := upper(coalesce(p_cost_currency, 'MXN'));
  v_rate numeric;
  v_unit_mxn numeric;
  v_item public.inventory_items;
  v_new_qty numeric;
  v_new_avg numeric;
  v_movement public.inventory_movements;
begin
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'INVENTORY_INVALID_QUANTITY' using errcode = '22023';
  end if;
  if p_unit_cost is null or p_unit_cost < 0 then
    raise exception 'INVENTORY_INVALID_COST' using errcode = '22023';
  end if;
  if v_currency not in ('USD', 'MXN') then
    raise exception 'INVENTORY_INVALID_CURRENCY' using errcode = '22023';
  end if;
  if v_currency = 'USD' and coalesce(p_exchange_rate, 0) <= 0 then
    raise exception 'INVENTORY_EXCHANGE_RATE_REQUIRED' using errcode = '22023';
  end if;

  if p_source_purchase_event_id is not null and not exists (
    select 1
    from public.project_purchase_events e
    join public.project_purchase_lines l on l.id = e.project_purchase_line_id
    where e.id = p_source_purchase_event_id
      and l.product_id = p_product_id
  ) then
    raise exception 'INVENTORY_SOURCE_EVENT_MISMATCH' using errcode = '22023';
  end if;

  v_rate := case when v_currency = 'USD' then p_exchange_rate else null end;
  v_unit_mxn := round(p_unit_cost * coalesce(v_rate, 1), 4);

  v_item := public.inventory_lock_item(p_product_id, p_location);
  v_new_qty := v_item.quantity_available + p_quantity;
  v_new_avg := case
    when v_item.quantity_available <= 0 then v_unit_mxn
    else round(
      (v_item.quantity_available * v_item.average_cost_mxn + p_quantity * v_unit_mxn) / v_new_qty,
      4
    )
  end;

  update public.inventory_items
  set quantity_available = v_new_qty,
      average_cost_mxn = v_new_avg,
      last_movement_at = now(),
      updated_at = now()
  where id = v_item.id;

  insert into public.inventory_movements (
    inventory_item_id, product_id, location, movement_type, quantity,
    unit_cost, cost_currency, exchange_rate, unit_cost_mxn, total_cost_mxn,
    quantity_after, average_cost_mxn_after, source_purchase_event_id,
    supplier_id, invoice_reference, notes, created_by_user_id
  ) values (
    v_item.id, p_product_id, v_item.location, 'in', p_quantity,
    p_unit_cost, v_currency, v_rate, v_unit_mxn, round(p_quantity * v_unit_mxn, 2),
    v_new_qty, v_new_avg, p_source_purchase_event_id,
    p_supplier_id, nullif(btrim(p_invoice_reference), ''), nullif(btrim(p_notes), ''),
    p_created_by_user_id
  )
  returning * into v_movement;

  return v_movement;
end;
$$;

-- Ajuste fisico (conteo, merma, hallazgo). Delta con signo.
-- Un ajuste positivo entra a p_unit_cost_mxn (o al promedio vigente si es null).
create or replace function public.inventory_adjust(
  p_inventory_item_id bigint,
  p_quantity_delta numeric,
  p_unit_cost_mxn numeric default null,
  p_notes text default null,
  p_created_by_user_id uuid default null
) returns public.inventory_movements
language plpgsql
set search_path = public
as $$
declare
  v_item public.inventory_items;
  v_unit_mxn numeric;
  v_new_qty numeric;
  v_new_avg numeric;
  v_movement public.inventory_movements;
begin
  if p_quantity_delta is null or p_quantity_delta = 0 then
    raise exception 'INVENTORY_INVALID_QUANTITY' using errcode = '22023';
  end if;
  if nullif(btrim(coalesce(p_notes, '')), '') is null then
    raise exception 'INVENTORY_ADJUST_REASON_REQUIRED' using errcode = '22023';
  end if;

  select * into v_item
  from public.inventory_items
  where id = p_inventory_item_id
  for update;

  if not found then
    raise exception 'INVENTORY_ITEM_NOT_FOUND' using errcode = 'P0002';
  end if;

  v_new_qty := v_item.quantity_available + p_quantity_delta;
  if v_new_qty < 0 then
    raise exception 'INVENTORY_INSUFFICIENT_STOCK' using errcode = '22023';
  end if;

  if p_quantity_delta > 0 then
    if p_unit_cost_mxn is not null and p_unit_cost_mxn < 0 then
      raise exception 'INVENTORY_INVALID_COST' using errcode = '22023';
    end if;
    v_unit_mxn := round(coalesce(p_unit_cost_mxn, v_item.average_cost_mxn), 4);
    v_new_avg := case
      when v_item.quantity_available <= 0 then v_unit_mxn
      else round(
        (v_item.quantity_available * v_item.average_cost_mxn + p_quantity_delta * v_unit_mxn) / v_new_qty,
        4
      )
    end;
  else
    -- Una salida no cambia el costo promedio.
    v_unit_mxn := v_item.average_cost_mxn;
    v_new_avg := v_item.average_cost_mxn;
  end if;

  update public.inventory_items
  set quantity_available = v_new_qty,
      average_cost_mxn = v_new_avg,
      last_movement_at = now(),
      updated_at = now()
  where id = v_item.id;

  insert into public.inventory_movements (
    inventory_item_id, product_id, location, movement_type, quantity,
    unit_cost, cost_currency, exchange_rate, unit_cost_mxn, total_cost_mxn,
    quantity_after, average_cost_mxn_after, notes, created_by_user_id
  ) values (
    v_item.id, v_item.product_id, v_item.location, 'adjust', p_quantity_delta,
    v_unit_mxn, 'MXN', null, v_unit_mxn, round(abs(p_quantity_delta) * v_unit_mxn, 2),
    v_new_qty, v_new_avg, btrim(p_notes), p_created_by_user_id
  )
  returning * into v_movement;

  return v_movement;
end;
$$;

-- Salida a un proyecto: descuenta existencias y crea el evento de compra en MXN
-- al costo promedio (redondeado a 2 decimales por project_purchase_events.unit_cost).
-- No actualiza los totales de la linea: eso lo hace la app con
-- recalculatePurchaseLineTotals para no duplicar la formula aqui.
create or replace function public.inventory_consume_to_project(
  p_inventory_item_id bigint,
  p_project_purchase_line_id bigint,
  p_client_project_id bigint,
  p_quantity numeric,
  p_purchase_date date,
  p_notes text default null,
  p_created_by_user_id uuid default null
) returns public.inventory_movements
language plpgsql
set search_path = public
as $$
declare
  v_item public.inventory_items;
  v_line public.project_purchase_lines;
  v_new_qty numeric;
  v_event_unit_cost numeric;
  v_event_id bigint;
  v_movement public.inventory_movements;
begin
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'INVENTORY_INVALID_QUANTITY' using errcode = '22023';
  end if;

  select * into v_line
  from public.project_purchase_lines
  where id = p_project_purchase_line_id
  for update;

  if not found or v_line.client_project_id <> p_client_project_id then
    raise exception 'INVENTORY_LINE_NOT_IN_PROJECT' using errcode = 'P0002';
  end if;

  if p_quantity > greatest(v_line.quantity_required - v_line.quantity_purchased, 0) + 0.0001 then
    raise exception 'INVENTORY_EXCEEDS_PENDING' using errcode = '22023';
  end if;

  select * into v_item
  from public.inventory_items
  where id = p_inventory_item_id
  for update;

  if not found then
    raise exception 'INVENTORY_ITEM_NOT_FOUND' using errcode = 'P0002';
  end if;

  if v_line.product_id is distinct from v_item.product_id then
    raise exception 'INVENTORY_PRODUCT_MISMATCH' using errcode = '22023';
  end if;

  v_new_qty := v_item.quantity_available - p_quantity;
  if v_new_qty < 0 then
    raise exception 'INVENTORY_INSUFFICIENT_STOCK' using errcode = '22023';
  end if;

  v_event_unit_cost := round(v_item.average_cost_mxn, 2);

  insert into public.project_purchase_events (
    project_purchase_line_id, purchase_date, quantity, unit_cost, cost_currency,
    exchange_rate, supplier, invoice_reference, warehouse_status, notes
  ) values (
    v_line.id, coalesce(p_purchase_date, current_date), p_quantity, v_event_unit_cost, 'MXN',
    null, 'Almacén ALFA', null, 'received',
    concat_ws(' ', 'Consumo de almacén (' || v_item.location || ').', nullif(btrim(p_notes), ''))
  )
  returning id into v_event_id;

  update public.inventory_items
  set quantity_available = v_new_qty,
      last_movement_at = now(),
      updated_at = now()
  where id = v_item.id;

  insert into public.inventory_movements (
    inventory_item_id, product_id, location, movement_type, quantity,
    unit_cost, cost_currency, exchange_rate, unit_cost_mxn, total_cost_mxn,
    quantity_after, average_cost_mxn_after, client_project_id,
    project_purchase_line_id, project_purchase_event_id, notes, created_by_user_id
  ) values (
    v_item.id, v_item.product_id, v_item.location, 'out', p_quantity,
    v_item.average_cost_mxn, 'MXN', null, v_item.average_cost_mxn,
    round(p_quantity * v_item.average_cost_mxn, 2),
    v_new_qty, v_item.average_cost_mxn, p_client_project_id,
    v_line.id, v_event_id, nullif(btrim(p_notes), ''), p_created_by_user_id
  )
  returning * into v_movement;

  update public.inventory_movements
  set invoice_reference = 'INV-MOV-' || v_movement.id
  where id = v_movement.id
  returning * into v_movement;

  update public.project_purchase_events
  set invoice_reference = 'INV-MOV-' || v_movement.id
  where id = v_event_id;

  return v_movement;
end;
$$;

-- Las funciones solo se invocan desde el servidor (service_role) despues de
-- validar canManagePurchases. Nadie mas puede ejecutarlas por PostgREST.
revoke all on function public.inventory_lock_item(bigint, text) from public, anon, authenticated;
revoke all on function public.inventory_register_entry(bigint, text, numeric, numeric, text, numeric, bigint, bigint, text, text, uuid) from public, anon, authenticated;
revoke all on function public.inventory_adjust(bigint, numeric, numeric, text, uuid) from public, anon, authenticated;
revoke all on function public.inventory_consume_to_project(bigint, bigint, bigint, numeric, date, text, uuid) from public, anon, authenticated;

grant execute on function public.inventory_lock_item(bigint, text) to service_role;
grant execute on function public.inventory_register_entry(bigint, text, numeric, numeric, text, numeric, bigint, bigint, text, text, uuid) to service_role;
grant execute on function public.inventory_adjust(bigint, numeric, numeric, text, uuid) to service_role;
grant execute on function public.inventory_consume_to_project(bigint, bigint, bigint, numeric, date, text, uuid) to service_role;

