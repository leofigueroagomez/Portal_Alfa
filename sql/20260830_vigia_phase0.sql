-- El Vigia de ALFA OS - Fase 0: cimientos.
--
-- Crea la infraestructura de la capa autonoma de vigilancia:
--   vigia_sensor_runs   - una fila por corrida de un sensor
--   vigia_findings      - una fila por hallazgo, con deduplicacion por (sensor_id, fingerprint)
--   vigia_audit_log     - bitacora append-only de todo lo que el Vigia ve, propone y ejecuta
--   vigia_v_*           - vistas de deteccion para los primeros sensores (INT-*, CST-*)
--
-- Frentes de la Fase 1: integridad de datos (INT) y costos/margenes (CST).
-- Todo lo escribe el runner con el cliente admin (service_role), que salta RLS.
-- Las vistas y tablas se exponen a 'authenticated' solo para lectura (bandeja futura).
--
-- Aplicado a produccion el 2026-08-30 (migracion supabase "vigia_phase0"). Cambio
-- puramente aditivo: solo crea objetos nuevos (tablas vigia_*, vistas vigia_v_*,
-- policies sobre esas tablas nuevas). No toca ninguna tabla, columna ni RLS
-- existente. Reversible con: drop de las tablas y vistas vigia_*.

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------

create table if not exists public.vigia_sensor_runs (
  id bigint generated by default as identity primary key,
  sensor_id text not null,
  status text not null default 'running' check (status in ('running', 'ok', 'error')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  findings_count integer not null default 0,
  resolved_count integer not null default 0,
  error text,
  created_at timestamptz not null default now()
);

create index if not exists vigia_sensor_runs_sensor_idx
  on public.vigia_sensor_runs (sensor_id, started_at desc);

create table if not exists public.vigia_findings (
  id bigint generated by default as identity primary key,
  sensor_id text not null,
  fingerprint text not null,
  domain text not null,
  lane text not null check (lane in ('auto_aplicado', 'requiere_autorizacion', 'prestar_atencion')),
  severity text not null default 'medio' check (severity in ('info', 'bajo', 'medio', 'alto', 'critico')),
  confidence text not null default 'media' check (confidence in ('alta', 'media', 'baja')),
  title text not null,
  summary text not null,
  evidence jsonb not null default '{}'::jsonb,
  impact_mxn numeric(16,2),
  entity_type text,
  entity_id text,
  proposed_action jsonb,
  status text not null default 'abierto'
    check (status in ('abierto', 'reconocido', 'descartado', 'resuelto', 'auto_aplicado', 'expirado')),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  seen_count integer not null default 1,
  resolved_at timestamptz,
  decided_by text,
  decided_at timestamptz,
  decision_note text,
  run_id bigint references public.vigia_sensor_runs(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (sensor_id, fingerprint)
);

create index if not exists vigia_findings_status_idx on public.vigia_findings (status);
create index if not exists vigia_findings_domain_idx on public.vigia_findings (domain);
create index if not exists vigia_findings_lane_idx on public.vigia_findings (lane);
create index if not exists vigia_findings_last_seen_idx on public.vigia_findings (last_seen_at desc);
create index if not exists vigia_findings_entity_idx on public.vigia_findings (entity_type, entity_id);

create table if not exists public.vigia_audit_log (
  id bigint generated by default as identity primary key,
  event_type text not null,
  actor text not null default 'vigia',
  sensor_id text,
  finding_id bigint references public.vigia_findings(id) on delete set null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists vigia_audit_log_created_idx on public.vigia_audit_log (created_at desc);
create index if not exists vigia_audit_log_finding_idx on public.vigia_audit_log (finding_id);

